export type CountryCode = (typeof COUNTRY_CODES)[number];

const CODES = new Set<string>(COUNTRY_CODES);

export function isCountryCode(value: unknown): value is CountryCode {
  return typeof value === 'string' && CODES.has(value);
}

/**
 * País propuesto a partir de los idiomas del navegador («es-ES» → ES). Si ninguno indica
 * región, no se adivina: el jugador lo elige.
 */
export function countryFromLocales(locales: readonly string[]): CountryCode | null {
  for (const locale of locales) {
    const region = /[-_]([A-Za-z]{2})(?:[-_]|$)/.exec(locale)?.[1]?.toUpperCase();
    if (isCountryCode(region)) return region;
  }
  return null;
}

/** Bandera como emoji: dos «letras regionales» Unicode. */
export function flagEmoji(code: CountryCode): string {
  return String.fromCodePoint(...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}
